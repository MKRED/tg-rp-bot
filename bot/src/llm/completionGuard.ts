/**
 * Детектор непригодных ответов LLM: пустой текст или известная фраза-отказа.
 * Вынесен из client.ts отдельным модулем без зависимостей (config/logger), чтобы
 * покрываться юнит-тестом без подтягивания окружения.
 */

// Известные фразы-отказы, которые модель иногда отдаёт вместо контента — считаем их
// неудачной генерацией и ретраим. Сравнение — точное по trim (не includes), чтобы не
// зарубить легитимный ответ, цитирующий эту фразу. Пополняется по мере обнаружения.
export const REFUSAL_PHRASES = new Set<string>([
  "你好，我无法给到相关内容。",
]);

/**
 * Ответ непригоден (нужен retry), если текст ПУСТОЙ или это известная фраза-отказа.
 * Проверяем именно content (reasoning сюда не попадает: в стриминге копится только
 * delta.content, в обычном ответе берётся message.content) — пустой ответ с одним лишь
 * reasoning'ом даст content === "" и будет считаться неудачным.
 */
export function isUnusableCompletion(content: string): boolean {
  const trimmed = content.trim();
  return trimmed === "" || REFUSAL_PHRASES.has(trimmed);
}
