import { encode } from "gpt-tokenizer/encoding/o200k_base";

/**
 * Точный подсчёт токенов через BPE-токенайзер o200k_base (тот же, что у GPT-4o/o-моделей).
 * Используется как универсальная аппроксимация для произвольной модели OpenRouter: модель в
 * OpenRouter своя у каждого провайдера, но o200k даёт куда более честную оценку, чем грубое
 * len/4 — особенно на кириллице (len/4 калиброван под английский и занижает русский на 20–50%).
 *
 * ВАЖНО: на клиенте (webapp shared/text/tokens.ts → estimateTokens) сознательно осталась
 * лёгкая эвристика len/4 для «~подсказок» в формах — туда не тащим ~3 МБ словаря в Mini App.
 * Авторитетные числа (статистика, бюджет контекста) считает сервер этой функцией.
 */
export function countTokens(text: string): number {
  if (!text) return 0;
  return encode(text).length;
}
