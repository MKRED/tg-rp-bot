/**
 * Кавычки RP-разметки ↔ теги для машинного перевода. В RP-тексте "речь" и «мысль» — разная разметка
 * (webapp RpText/parseRpText), а переводчики ставят типографику целевого языка: Google на русском
 * делает из "речи" «ёлочки» (речь становится мыслью), на немецком — „…“, Яндекс и Google на некоторых
 * языках вовсе убирают кавычки и оформляют реплику тире. Поэтому до перевода речь уходит тегом <q>,
 * мысль — <cite>: оба движка переводят текст внутри и оставляют теги на месте (проверено живыми
 * запросами), а после перевода теги снова становятся кавычками.
 */

/** Те же пары, что у parseRpText: "речь" — прямые кавычки, «мысль» — ёлочки, обе могут быть многострочными. */
const RP_QUOTE = /"([^"]+)"|«([^»]+)»/g;

/** Теги, которыми помечаем кавычки; есть в исходном тексте — защиту не включаем (см. hasQuoteTags). */
const QUOTE_TAG = /<\/?(?:q|cite)>/i;

export function wrapRpQuotes(text: string): string {
  return text.replace(RP_QUOTE, (_, speech: string | undefined, thought: string | undefined) =>
    speech !== undefined ? `<q>${speech}</q>` : `<cite>${thought}</cite>`,
  );
}

/**
 * Обратно: <q>…</q> → "…", <cite>…</cite> → «…». Пробелы у краёв тега внутрь кавычек не тащим. Тире,
 * которое Яндекс ставит в начало реплики («- Я устал»), убираем: кавычки уже размечают речь.
 */
export function unwrapRpQuotes(text: string): string {
  return text
    .replace(/<q>[ \t]*(?:[-–—][ \t]+)?/gi, '"')
    .replace(/[ \t]*<\/q>/gi, '"')
    .replace(/<cite>[ \t]*/gi, "«")
    .replace(/[ \t]*<\/cite>/gi, "»");
}

/**
 * В тексте уже есть <q>/<cite> — например, переводят промпт с HTML. Тогда обратная замена превратила бы
 * их в кавычки, поэтому для Google (он шлёт текст как есть) такой текст переводим без защиты кавычек.
 */
export function hasQuoteTags(text: string): boolean {
  return QUOTE_TAG.test(text);
}
