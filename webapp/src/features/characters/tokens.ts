/**
 * Грубая оценка числа токенов: ~4 символа на токен.
 *
 * Точный счёт невозможен — модель в OpenRouter произвольная, у каждой свой токенайзер.
 * Поэтому это ориентир (показываем с тильдой «~N»), а не точное значение; зато без
 * тяжёлых таблиц энкодинга в бандле и мгновенно при вводе.
 */
export function estimateTokens(text: string): number {
  if (!text) return 0;
  return Math.ceil(text.length / 4);
}
