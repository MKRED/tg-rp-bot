/**
 * Индекс первого отрисовываемого сообщения ленты.
 *
 * `frozen` — зафиксированный индекс начала окна (null — ещё не зафиксирован, окно = последние `step`).
 * Начало фиксируется, а не считается от конца каждый раз: иначе при добавлении новых сообщений окно
 * «ехало» бы вниз, и верхние пузыри исчезали бы из-под глаз читающего историю пользователя.
 * Сверху ограничиваем `total - step`, чтобы после укорачивания ленты (смена ветки, удаление,
 * оптимистичный реген) на экране всегда оставалось хотя бы `step` сообщений.
 */
export function renderWindowStart(frozen: number | null, total: number, step: number): number {
  const tailStart = Math.max(0, total - step);
  return frozen === null ? tailStart : Math.min(frozen, tailStart);
}
