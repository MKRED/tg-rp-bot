/** Слово «Привет» на разных языках мира — для рандомного приветствия на главной. */
const GREETINGS = [
  "Привет",      // русский
  "Hello",       // английский
  "Hola",        // испанский
  "Bonjour",     // французский
  "Ciao",        // итальянский
  "Hallo",       // немецкий
  "こんにちは",   // японский
  "你好",         // китайский
  "안녕하세요",   // корейский
  "مرحبا",       // арабский
  "Olá",         // португальский
  "Merhaba",     // турецкий
  "Hej",         // шведский / датский
  "Hei",         // финский / норвежский
  "Ahoj",        // чешский / словацкий
  "Cześć",       // польский
  "Γεια",        // греческий
  "Xin chào",    // вьетнамский
  "नमस्ते",      // хинди
  "Habari",      // суахили
  "Sawubona",    // зулу
  "Salut",       // румынский
  "Szia",        // венгерский
  "Tere",        // эстонский
  "Labas",       // литовский
] as const;

export function randomGreeting(): string {
  return GREETINGS[Math.floor(Math.random() * GREETINGS.length)]!;
}
